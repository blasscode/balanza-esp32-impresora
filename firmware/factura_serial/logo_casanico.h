// Uso en factura_simulada: llamar imprimirLogo() después de iniciar().
// Manda el logo en bloques de hasta 255 filas con GS v 0.
void imprimirLogo() {
  for (uint16_t y = 0; y < LOGO_ALTO; y += 255) {
    uint16_t n = (LOGO_ALTO - y > 255) ? 255 : (LOGO_ALTO - y);
    cmd({0x1D, 'v', '0', 0, LOGO_BYTES_FILA, 0, (uint8_t)(n & 0xFF), (uint8_t)(n >> 8)});
    for (uint32_t i = (uint32_t)y * LOGO_BYTES_FILA; i < (uint32_t)(y + n) * LOGO_BYTES_FILA; i++)
      add(pgm_read_byte(&LOGO_CASANICO[i]));
  }
}
